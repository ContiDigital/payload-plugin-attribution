const DEFAULT_DIGITS = 2

export function currencyDigits(currency: string): number {
  if (!ACTIVE_CURRENCIES.has(currency)) {
    throw new TypeError('payload-plugin-attribution: invalid currency code')
  }
  return NON_DEFAULT_DIGITS[currency] ?? DEFAULT_DIGITS
}

export function toMajorUnits(minor: number, currency: string): number {
  return minor / 10 ** currencyDigits(currency)
}

export function isMinorUnits(value: unknown): value is number {
  return typeof value === 'number' && Number.isSafeInteger(value) && value >= 0
}
